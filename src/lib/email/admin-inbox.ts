// The one inbox for Boca Banker. Replies are addressed to a per-thread
// plus-address on the receiving domain (team+<threadId>@bocabanker.com —
// see inbound-address.ts). The routes are admin-only and the platform has a
// single admin, so the service does not scope rows by owner.

// ── Spam filter ──

const SPAM_PATTERNS = [
  /\b(viagra|cialis|casino|lottery|prince|inheritance)\b/i,
  /\b(unsubscribe.*click here|click here now|act now|limited time|free money)\b/i,
  /\b(make money fast|earn extra cash|no obligation|you have been selected|congratulations you won)\b/i,
  /\b(bitcoin.*invest|crypto.*guaranteed|guaranteed return|cryptocurrency opportunity)\b/i,
  /\b(nigerian|wire transfer|western union)\b/i,
];

const SPAM_TLDS = ['.xyz', '.top', '.click', '.bid', '.win', '.loan', '.buzz', '.icu'];

/** Bulk senders nobody answers: filed as spam, still recoverable. */
const SPAM_SENDER_LOCAL_PARTS = /^(newsletter|marketing|promo(tions?)?|offers?|deals?)$/i;

export function isLikelySpam(email: { from: string; subject: string; text?: string | null }): boolean {
  const content = `${email.subject} ${email.text || ''}`;
  const matchCount = SPAM_PATTERNS.filter((p) => p.test(content)).length;
  const [local = '', fromDomain = ''] = email.from.toLowerCase().split('@');
  const isSpamTLD = SPAM_TLDS.some((tld) => fromDomain.endsWith(tld));
  return matchCount >= 2 || isSpamTLD || SPAM_SENDER_LOCAL_PARTS.test(local);
}

// ── Metadata (JSON in emails.metadata) ──

export interface EmailAttachmentMeta {
  id: string;
  filename: string;
  contentType: string;
  size?: number;
}

export interface EmailMetadata {
  /** RFC Message-ID of an inbound email (bare, no angle brackets). */
  messageId?: string;
  /** Threading headers we sent (In-Reply-To / References). */
  headers?: Record<string, string>;
  cc?: string[];
  attachments?: EmailAttachmentMeta[];
  /** Set on the "Send me a test" row so the UI can label it. */
  test?: boolean;
  /** Auto-responder / list mail — never classified or auto-replied. */
  autoGenerated?: boolean;
  /** Legacy flag from before the is_spam column. */
  spamFiltered?: boolean;
}

export function readMetadata(raw: unknown): EmailMetadata {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return {};
  return raw as EmailMetadata;
}

// ── Folders ──

export const INBOX_FOLDERS = ['inbox', 'unread', 'starred', 'sent', 'spam'] as const;
export type InboxFolder = (typeof INBOX_FOLDERS)[number];

export function isInboxFolder(v: unknown): v is InboxFolder {
  return typeof v === 'string' && (INBOX_FOLDERS as readonly string[]).includes(v);
}

function folderCondition(folder: InboxFolder) {
  switch (folder) {
    case 'inbox':
      return and(eq(emails.direction, 'inbound'), eq(emails.isSpam, false));
    case 'unread':
      return and(eq(emails.direction, 'inbound'), eq(emails.isSpam, false), eq(emails.isRead, false));
    case 'starred':
      return and(eq(emails.isStarred, true), eq(emails.isSpam, false));
    case 'sent':
      return eq(emails.direction, 'outbound');
    case 'spam':
      return eq(emails.isSpam, true);
  }
}

export const BULK_ACTIONS = ['markRead', 'markUnread', 'star', 'unstar', 'spam', 'notSpam', 'delete'] as const;
export type BulkAction = (typeof BULK_ACTIONS)[number];

export function isBulkAction(v: unknown): v is BulkAction {
  return typeof v === 'string' && (BULK_ACTIONS as readonly string[]).includes(v);
}

